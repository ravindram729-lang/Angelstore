const fs=require('fs');
const path=require('path');
const crypto=require('crypto');
const root=__dirname;
const storageRoot=path.resolve(process.env.ANGELSTORE_STORAGE_DIR||root);
const uploadRoot=path.resolve(process.env.ANGELSTORE_UPLOAD_DIR||path.join(storageRoot,'uploads','payments'));
const backupRoot=path.resolve(process.env.ANGELSTORE_BACKUP_DIR||path.join(storageRoot,'backups'));
const production=String(process.env.NODE_ENV||'').toLowerCase()==='production';
const checks=[];
function check(name,ok,detail){checks.push({name,ok:Boolean(ok),detail:String(detail||'')})}
check('NODE_ENV',production,'Set NODE_ENV=production on the real host.');
const secret=process.env.ANGELSTORE_AUTH_SECRET||'';
check('Auth secret',secret.length>=32,'ANGELSTORE_AUTH_SECRET must be at least 32 characters.');
check('Admin username',!!process.env.ANGELSTORE_ADMIN_USER,'ANGELSTORE_ADMIN_USER must be set.');
check('Admin password',String(process.env.ANGELSTORE_ADMIN_PASS||'').length>=12,'ANGELSTORE_ADMIN_PASS must be at least 12 characters.');
const origin=String(process.env.ANGELSTORE_CORS_ORIGIN||'');
const corsOrigins=origin.split(',').map(x=>x.trim()).filter(Boolean);
check('CORS origin',corsOrigins.length>0&&corsOrigins.every(x=>/^https:\/\/[^*\s]+$/i.test(x)),'Use one or more explicit HTTPS origins, comma-separated; do not use *.');
check('Storage root',fs.existsSync(storageRoot),'ANGELSTORE_STORAGE_DIR should point to persistent disk in production.');
check('data.json',true,fs.existsSync(path.join(storageRoot,'data.json'))?'Database file exists.':'Database file will be created on first boot; verify persistence after startup.');
check('Backup directory',fs.existsSync(backupRoot),'Backup directory must be persistent on the hosting platform.');
check('Payment upload directory',fs.existsSync(uploadRoot),'Payment-proof directory must be persistent.');
if(production)check('Persistent storage configuration',!!process.env.ANGELSTORE_STORAGE_DIR,'Set ANGELSTORE_STORAGE_DIR to the host persistent-disk mount; local app-directory storage is not durable on ephemeral hosts.');
check('Service catalog',fs.existsSync(path.join(root,'service-catalog.js')),'Service catalog is present.');
check('Storage module',fs.existsSync(path.join(root,'storage.js')),'Storage module is present.');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
check('Start script',pkg.scripts&&pkg.scripts.start==='node server.js','package.json start script must be node server.js.');
const result={ok:checks.every(x=>x.ok),production,generated_at:new Date().toISOString(),checks};
console.log(JSON.stringify(result,null,2));
if(!result.ok)process.exit(1);
